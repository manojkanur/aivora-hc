from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any

from app.config import settings

# Keys that are metadata, not content
SKIP_KEYS = {"skill_slug", "generated_at", "tool_name", "tool_input", "raw_text"}


def _get_source(draft_content: dict[str, Any]) -> dict[str, Any]:
    """Return the content fields to render, supporting both old tool_input and new flat format."""
    tool_input = draft_content.get("tool_input")
    if tool_input and isinstance(tool_input, dict):
        return tool_input
    return {k: v for k, v in draft_content.items() if k not in SKIP_KEYS and v}


def _get_title(draft_content: dict[str, Any], source: dict[str, Any]) -> str:
    skill_slug = draft_content.get("skill_slug", "hc-advisory")
    return skill_slug.replace("-", " ").title()


def _get_org_name(source: dict[str, Any], title: str) -> str:
    name = source.get("org_name", "")
    if not name:
        summary = source.get("executive_summary", "")
        name = summary[:50].split(".")[0] if summary else title
    return name or title


def _flatten_value(value: Any) -> str:
    """Flatten any value to a readable string."""
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, list):
        parts = []
        for item in value:
            if isinstance(item, str):
                parts.append(f"• {item}")
            elif isinstance(item, dict):
                sub = ", ".join(f"{k}: {_flatten_value(v)}" for k, v in list(item.items())[:3])
                parts.append(f"• {sub}")
            else:
                parts.append(f"• {item}")
        return "\n".join(parts)
    if isinstance(value, dict):
        return "\n".join(f"{k.replace('_',' ').title()}: {_flatten_value(v)}" for k, v in value.items())
    return str(value)


