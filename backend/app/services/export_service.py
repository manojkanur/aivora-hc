def generate_pptx(draft_content: dict[str, Any], brand_kit: dict[str, Any]) -> bytes:
    """Generate a PowerPoint from draft content — one slide per section."""
    from pptx import Presentation
    from pptx.dml.color import RGBColor
    from pptx.util import Inches, Pt

    def _rgb(hex_color: str) -> RGBColor:
        h = hex_color.lstrip("#")
        return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))

    primary_hex = brand_kit.get("primary_color", "#1A1A2E")
    font_name = brand_kit.get("font", "Calibri")

    source = _get_source(draft_content)
    title = _get_title(draft_content, source)
    org_name = _get_org_name(source, title)

    prs = Presentation()
    prs.slide_width = Inches(13.33)
    prs.slide_height = Inches(7.5)

    # --- Title slide ---
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    if slide.shapes.title:
        slide.shapes.title.text = org_name
        slide.shapes.title.text_frame.paragraphs[0].font.size = Pt(36)
        slide.shapes.title.text_frame.paragraphs[0].font.color.rgb = _rgb(primary_hex)
        slide.shapes.title.text_frame.paragraphs[0].font.name = font_name
    if len(slide.placeholders) > 1:
        slide.placeholders[1].text = (
            f"{title} · Generated by Aivora HC · {datetime.now(timezone.utc).strftime('%B %Y')}"
        )

    # --- One content slide per section ---
    for key, value in source.items():
        if not value:
            continue
        label = key.replace("_", " ").title()
        body_text = _flatten_value(value)
        if not body_text.strip():
            continue

        slide = prs.slides.add_slide(prs.slide_layouts[1])
        if slide.shapes.title:
            slide.shapes.title.text = label
            slide.shapes.title.text_frame.paragraphs[0].font.color.rgb = _rgb(primary_hex)
            slide.shapes.title.text_frame.paragraphs[0].font.name = font_name
            slide.shapes.title.text_frame.paragraphs[0].font.size = Pt(24)

        if len(slide.placeholders) > 1:
            tf = slide.placeholders[1].text_frame
            tf.word_wrap = True
            tf.text = body_text[:2500]
            for para in tf.paragraphs:
                para.font.name = font_name
                para.font.size = Pt(13)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


