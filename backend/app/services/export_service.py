# PDF generation (ReportLab)
# ---------------------------------------------------------------------------

def generate_pdf(draft_content: dict[str, Any], brand_kit: dict[str, Any]) -> bytes:
    """Generate a PDF using ReportLab with proper rendering of the new flat content structure."""
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import (
        HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    )

    def _hex(h: str) -> colors.HexColor:
        return colors.HexColor(h if h.startswith("#") else f"#{h}")

    primary_hex = brand_kit.get("primary_color", "#C9A84C")
    secondary_hex = brand_kit.get("secondary_color", "#E2C87A")
    primary = _hex(primary_hex)
    secondary = _hex(secondary_hex)

    source = _get_source(draft_content)
    title = _get_title(draft_content, source)
    org_name = _get_org_name(source, title)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=2*cm, rightMargin=2*cm,
        topMargin=2*cm, bottomMargin=2*cm,
    )

    styles = getSampleStyleSheet()
    style_h1 = ParagraphStyle("H1", parent=styles["Heading1"],
        textColor=primary, fontSize=20, spaceAfter=6)
    style_h2 = ParagraphStyle("H2", parent=styles["Heading2"],
        textColor=primary, fontSize=13, spaceBefore=14, spaceAfter=4)
    style_body = ParagraphStyle("Body", parent=styles["Normal"],
        fontSize=10, leading=15, spaceAfter=4)
    style_bullet = ParagraphStyle("Bullet", parent=styles["Normal"],
        fontSize=10, leading=14, leftIndent=12, spaceAfter=2,
        bulletText="•", bulletIndent=4)
    style_meta = ParagraphStyle("Meta", parent=styles["Normal"],
        fontSize=9, textColor=colors.HexColor("#888888"), spaceAfter=16)

    story = []

    # Header
    story.append(Paragraph(f"{org_name}", style_h1))
    story.append(Paragraph(f"{title}", ParagraphStyle("Sub", parent=styles["Normal"],
        fontSize=14, textColor=secondary, spaceAfter=4)))
    story.append(Paragraph(
        f"Generated by Aivora HC · {datetime.now(timezone.utc).strftime('%d %B %Y')}",
        style_meta))
    story.append(HRFlowable(width="100%", thickness=2, color=primary))
    story.append(Spacer(1, 0.4*cm))

    for key, value in source.items():
        if not value:
            continue
        label = key.replace("_", " ").title()
        story.append(Paragraph(label, style_h2))

        if isinstance(value, str):
            for para in value.split("\n"):
                if para.strip():
                    story.append(Paragraph(para.strip(), style_body))
        elif isinstance(value, list):
            if all(isinstance(v, str) for v in value):
                for item in value:
                    story.append(Paragraph(str(item), style_bullet))
            elif all(isinstance(v, dict) for v in value):
                # Table for list of objects — use Paragraph cells so text wraps
                style_th = ParagraphStyle("TH", parent=styles["Normal"],
                    fontSize=8, leading=11, textColor=colors.HexColor("#111111"),
                    fontName="Helvetica-Bold")
                style_td = ParagraphStyle("TD", parent=styles["Normal"],
                    fontSize=8, leading=11, textColor=colors.HexColor("#1A1A1A"),
                    wordWrap="CJK")
                rows_data = []
                if value:
                    headers = list(value[0].keys())
                    rows_data.append([
                        Paragraph(h.replace("_", " ").title(), style_th)
                        for h in headers
                    ])
                    for item in value:
                        row = []
                        for h in headers:
                            cell_text = _flatten_value(item.get(h, ""))
                            row.append(Paragraph(cell_text, style_td))
                        rows_data.append(row)
                if rows_data:
                    col_count = len(rows_data[0])
                    col_width = (A4[0] - 4*cm) / col_count
                    tbl = Table(rows_data, colWidths=[col_width]*col_count,
                                repeatRows=1, splitByRow=True)
                    tbl.setStyle(TableStyle([
                        ("BACKGROUND",    (0, 0), (-1, 0),  primary),
                        ("ROWBACKGROUNDS",(0, 1), (-1, -1), [colors.HexColor("#FFFFFF"), colors.HexColor("#FAFAFA")]),
                        ("GRID",          (0, 0), (-1, -1), 0.5, primary),
                        ("LINEBELOW",     (0, 0), (-1, 0),  1.5, primary),
                        ("VALIGN",        (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING",    (0, 0), (-1, -1), 5),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                        ("LEFTPADDING",   (0, 0), (-1, -1), 6),
                        ("RIGHTPADDING",  (0, 0), (-1, -1), 6),
                    ]))
                    story.append(tbl)
            else:
                for item in value:
                    story.append(Paragraph(_flatten_value(item), style_bullet))
        elif isinstance(value, dict):
            for k, v in value.items():
                story.append(Paragraph(
                    f"<b>{k.replace('_', ' ').title()}:</b> {_flatten_value(v)}",
                    style_body))
        else:
            story.append(Paragraph(str(value), style_body))

        story.append(Spacer(1, 0.2*cm))

    # Footer
    story.append(Spacer(1, 0.5*cm))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cccccc")))
    story.append(Paragraph(
        f"Confidential · Aivora HC Platform · {datetime.now(timezone.utc).year}",
        ParagraphStyle("Footer", parent=styles["Normal"], fontSize=8,
            textColor=colors.HexColor("#aaaaaa"), spaceBefore=6)))

    doc.build(story)
    return buf.getvalue()


