def generate_docx(draft_content: dict[str, Any], brand_kit: dict[str, Any]) -> bytes:
    """Generate a Word document from draft content."""
    from docx import Document
    from docx.shared import Pt, RGBColor

    def _rgb(hex_color: str) -> RGBColor:
        h = hex_color.lstrip("#")
        return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))

    primary_color = _rgb(brand_kit.get("primary_color", "#1A1A2E"))
    font_name = brand_kit.get("font", "Calibri")

    source = _get_source(draft_content)
    title = _get_title(draft_content, source)
    org_name = _get_org_name(source, title)

    doc = Document()

    # Title
    title_para = doc.add_heading(level=0)
    run = title_para.add_run(f"{org_name} — {title}")
    run.font.name = font_name
    run.font.color.rgb = primary_color
    run.font.size = Pt(26)

    # Subtitle
    sub = doc.add_paragraph()
    sub_run = sub.add_run(f"Generated by Aivora HC  |  {datetime.now(timezone.utc).strftime('%B %Y')}")
    sub_run.font.size = Pt(11)
    sub_run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
    doc.add_paragraph()

    for key, value in source.items():
        if not value:
            continue
        label = key.replace("_", " ").title()

        heading = doc.add_heading(label, level=1)
        for run in heading.runs:
            run.font.color.rgb = primary_color
            run.font.name = font_name

        if isinstance(value, str):
            for line in value.split("\n"):
                if line.strip():
                    doc.add_paragraph(line.strip())
        elif isinstance(value, list):
            if all(isinstance(v, str) for v in value):
                for item in value:
                    p = doc.add_paragraph(style="List Bullet")
                    p.add_run(str(item))
            elif all(isinstance(v, dict) for v in value):
                # Table
                if value:
                    headers = list(value[0].keys())
                    table = doc.add_table(rows=1, cols=len(headers))
                    table.style = "Light Grid Accent 1"
                    for i, h in enumerate(headers):
                        table.rows[0].cells[i].text = h.replace("_", " ").title()
                    for item in value:
                        row = table.add_row()
                        for i, h in enumerate(headers):
                            row.cells[i].text = _flatten_value(item.get(h, ""))[:300]
            else:
                for item in value:
                    p = doc.add_paragraph(style="List Bullet")
                    p.add_run(_flatten_value(item))
        elif isinstance(value, dict):
            for k, v in value.items():
                p = doc.add_paragraph()
                run = p.add_run(f"{k.replace('_', ' ').title()}: ")
                run.bold = True
                p.add_run(_flatten_value(v))
        else:
            doc.add_paragraph(str(value))

        doc.add_paragraph()

    # Footer
    footer = doc.add_paragraph("Confidential – Aivora HC Platform")
    footer.runs[0].font.size = Pt(9)
    footer.runs[0].font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
